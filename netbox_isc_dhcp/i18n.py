def tmsg(text: str) -> str:
    """Translate a validation message of the pure code (English) to the current language."""
    if current_language() != "sk":
        return text
    if text.startswith("individual code: "):
        return "individuálny kód: " + tmsg(text[len("individual code: "):])
    if text in _MSG_SK:
        return _MSG_SK[text]
    import re

    for pat, rep in _MSG_SK_PATTERNS:
        if re.fullmatch(pat, text):
            return re.sub(pat, rep, text)
    return text


def t(key: str, **kw) -> str:
    if key not in TR:  # a missing translation must never break a page
        return key
    sk, en = TR[key]
    text = en if current_language() == "en" else sk
    return text.format(**kw) if kw else text


t_lazy = lazy(t, str)


